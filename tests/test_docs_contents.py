"""The contents lists at the top of docs/DEVELOPMENT.md and docs/OPERATIONS.md.

Each file is thousands of lines long with dozens of `##` sections, and the 2026-10-29 review
found new features documented nowhere partly because nobody could see what was there. Each
opens with a contents list, one link per `##` heading, between the CONTENTS markers. The test
fails when a section is added, renamed or removed without the list following it; to rebuild
the lists, run this file:

    python tests/test_docs_contents.py --write

Links use GitHub's heading anchors: lower case, punctuation other than `-` and `_` dropped,
spaces as `-`, and `-1`, `-2` added to a repeated heading.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DOCS = ("docs/DEVELOPMENT.md", "docs/OPERATIONS.md")
START = "<!-- CONTENTS: generated by tests/test_docs_contents.py --write -->"
END = "<!-- /CONTENTS -->"


def headings(text: str) -> list[str]:
    """Every `## ` heading outside fenced code blocks, in order."""
    found, fenced = [], False
    for line in text.split("\n"):
        if line.startswith("```"):
            fenced = not fenced
        elif not fenced and line.startswith("## "):
            found.append(line[3:].strip())
    return found


def anchor(heading: str, seen: dict[str, int]) -> str:
    slug = re.sub(r"[^\w\- ]", "", heading.lower()).replace(" ", "-")
    count = seen.get(slug, 0)
    seen[slug] = count + 1
    return slug if count == 0 else f"{slug}-{count}"


def contents(text: str) -> str:
    seen: dict[str, int] = {}
    rows = [f"- [{h.replace('`', '')}](#{anchor(h, seen)})" for h in headings(text)]
    return "\n".join([START, "", "Contents:", "", *rows, "", END])


def with_contents(text: str) -> str:
    """The file with its contents list rebuilt, placed before the first `##` heading."""
    if START in text:
        before, rest = text.split(START, 1)
        after = rest.split(END, 1)[1]
        text = before + after.lstrip("\n")
    first = text.index("\n## ")
    return text[: first + 1] + contents(text) + "\n\n" + text[first + 1 :]


def test_each_long_doc_lists_its_sections():
    for name in DOCS:
        text = (REPO / name).read_text(encoding="utf-8")
        fix = f"run python {__file__} --write"
        assert START in text and END in text, f"{name} has no contents list; {fix}"
        assert with_contents(text) == text, f"{name}'s contents list is out of date; {fix}"


def test_contents_anchors_follow_github():
    seen: dict[str, int] = {}
    osm = "fixing-osm-from-a-ride-scriptsosm_editpy"
    assert anchor("Fixing OSM from a ride (scripts/osm_edit.py)", seen) == osm
    assert anchor("Phone app (v0.8.0)", seen) == "phone-app-v080"
    assert anchor("Phone app (v0.8.0)", seen) == "phone-app-v080-1"


if __name__ == "__main__" and "--write" in sys.argv:
    for name in DOCS:
        path = REPO / name
        path.write_text(with_contents(path.read_text(encoding="utf-8")), encoding="utf-8")
