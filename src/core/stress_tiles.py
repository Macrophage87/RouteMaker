# 67). One tile serves every ride time, so the pre-draw draws each tile once.
OPTIONAL_EXPRESSIONS = {
    "car_free": f"NULLIF(array_to_string(s.{CAR_FREE_COLUMN}, ','), '')",
    "separate_bikeway": f"NULLIF(s.{SEPARATE_BIKEWAY_COLUMN}, false)",
    "mtb": f"NULLIF(s.{MTB_ONLY_COLUMN}, false)",
    "rough": f"NULLIF(s.{ROUGH_COLUMN}, false)",
    "roadside": f"NULLIF(s.{ROADSIDE_COLUMN}, false)",
    "half": f"NULLIF(s.{STRESS_HALF_COLUMN}, false)",
    "scenic": f"CASE WHEN s.{SCENIC_COLUMN} IS NOT NULL THEN true END",
    "contraflow": f"CASE WHEN s.{FACILITY_SHOWN_COLUMN} IS NOT NULL THEN true END",
    "popular": f"NULLIF(s.{BIKE_POPULAR_COLUMN}, 0)",
    "link": f"NULLIF(s.{ROAD_LINK_COLUMN}, false)",
    "overview": f"NULLIF(s.{OVERVIEW_COLUMN}, 0)",
    # `rpm`: the Mass Ride capacity, riders a minute, rounded DOWN to a multiple of
    # RPM_STEP. The Mass Ride bands (60, 120, 200) are multiples of it, so a
    # feature never moves band; and the zoomed-out levels, which collect every
    # segment of one value into one feature, are not split into a feature per
    # distinct figure (one per integer would be about 400 values a class).
    "rpm": (
        f"(floor(round(s.{MASS_WIDTH_COLUMN}::numeric * {RPM_PER_METRE_SQL}) / {RPM_STEP}.0)"
        f" * {RPM_STEP})::int"
    ),
}

# A short bridge inside a trail is drawn in its trail's surface, not its deck's, where the
# rebuild has judged it (`trail_bridge`: 1 between paved trail ways, 2 where an end is
# unpaved; `pipeline.trail_routes.judge_bridges`). The owner, 2026-10-09, on the C&O
# towpath's Seneca Aqueduct drawn as a paved path in the middle of the unpaved towpath:
# "We made woodden bridges paved, so they didn't mess with the paved routing. Now it makes
# the unpaved routing look weird." The deck stays paved for routing and in the road panel
# (OWNER-DECISIONS 440, `segment.is_unpaved`); only the map's surface mark follows the
# trail, as the zoomed-out rule already judges it (`long_trails_predicate`). Any other way,
# and a bridge the rebuild left to its own deck (0), is drawn as `is_unpaved` holds it.
BRIDGE_UNPAVED = (
    f"CASE WHEN s.{TRAIL_BRIDGE_COLUMN} = 2 THEN true "
    f"WHEN s.{TRAIL_BRIDGE_COLUMN} = 1 THEN false ELSE s.is_unpaved END"
)

# What an optional property is drawn from on a table without its column: the
# facility is derived from the trail network (an off-road path, or nothing),
# so the trails carry the path's rails at every zoom before the column exists;
# and a road beside a separate bikeway is not known, so none is drawn faint
# for it.
FALLBACKS = {"facility": TRAIL_NETWORK_FACILITY}

# THE MOUNTAIN-BIKE TRAILS ZOOMED OUT. The owner, 2026-10-28: "When on Mountain bike mode, you
# should generally show the mountain bike trails at any zoom so people can see them." So the
# zoomed-out levels (z7-11) keep every mountain-bike-only way beside the long trails, merged and
# simplified as the rest; the front end draws them that far out in the Mountain Bike ride type
# alone (stressStyle.js, `mtbMinZoom`), and every other ride type leaves them out below z12 as
# before (its routable layers cut them, `mtbHides`, and the trail layer starts at z12). Only on a
# table with the column; the map class's own rule (a road) still applies after it.
ZOOMED_OUT_MTB = f"s.{MTB_ONLY_COLUMN}"

# A rated trail's two OSM difficulty scales as mapped (the owner, 2026-10-28: "say which rating
# type triggered the rating and if they are rated on both scales say that"), read from the kept
# tags (`segment.trail_tags`, `routemaker.trail_facts.KEYS`) on a table that has them. The front end
# says which one set the level (lib/featureHover.ts). Left out where none is mapped: a table built
# before the rebuild that keeps the scales carries neither, and the card says both as before.
MTB_SCALE_PROPERTIES = {"mtb_scale": "mtb:scale", "mtb_imba": "mtb:scale:imba"}

# The three columns the long-trails rule reads (OWNER-DECISIONS 375, 377), which the
# rebuild writes from the OSM route relations and way names
# (`pipeline.trail_routes`). Not carried in a tile: they only choose which ways
# the z10-11 tiles hold. A table promoted before them has none of them, and its
# zoomed-out tiles keep every path and trail, as they did; the rule applies
# only where all three are there. A data rebuild adds them; nothing else does.
LONG_TRAIL_COLUMNS = (TRAIL_ROUTE_COLUMN, TRAIL_RUN_COLUMN, TRAIL_BRIDGE_COLUMN)


# THE MAJOR TRAILS' NAMES. The owner, 2026-10-21: "Major off road bike trails like the
# Metropolitan Branch Trail should be named on the map." A way carries its trail's name as
# `trail_name` (the way's OSM name, else its long route relation's: `segment.trail_name`,
# `pipeline.trail_routes.way_name`) where it is one of the long trails the z11 map keeps:
# a traffic-free path (`trails_predicate`, not a road closed to cars only at set times,
# which keeps its street name) on a regional-or-larger bicycle route or a long walking
# route, or in a named run of 2.5 mi or more (5 mi and a long bicycle route if unpaved;
# Z11_LONG_TRAILS, OWNER-DECISIONS 375-380), from z12. So "major" is the rule the zoomed-out map
# already draws by, not a list. Left out of every other way, and of a table without the
# long-trail columns, which the same rebuild writes `trail_name` with. The map draws it
# along the line (frontend/src/stressStyle.js, TRAIL_LABEL). A mountain-bike trail's
# name is `name` (MTB_NAME_COLUMN), not this.
#
# And a major corridor's (the owner, 2026-10-23: "the trails should be lableled at this zoom"
# ... "and the major corridors"): a way of the top popular class carries its `trail_name`
# too, which the rebuild gives a named corridor's ways (`pipeline.major_corridors.apply`)
# and a long calm road already has, so Q Street or the 15th Street lane is named where the
# zoomed-out map draws it: at z10-11 only, as from z12 the base map names the street itself
# (a second name, in the off-road paths' purple, would read as a trail). Only on a table with
# `bike_popular`.
POPULAR_NAMED_MIN_CLASS = 3


def trail_name_rule(has_facility: bool, has_popular: bool = False) -> str:
    corridor = (
        f" WHEN s.{BIKE_POPULAR_COLUMN} >= {POPULAR_NAMED_MIN_CLASS} THEN s.{TRAIL_NAME_COLUMN}"
        if has_popular
        else ""
    )
    return (
        f"CASE WHEN {trails_predicate(has_facility)} AND "
        f"{long_trails_predicate(Z11_LONG_TRAILS)} THEN s.{TRAIL_NAME_COLUMN}{corridor} END"
    )


# THE LONG CALM STREETS. The owner, 2026-10-21: "When the roads get crowded with zoom, go in this
# rough priority: Off road path, protected bike lane, painted bike lane, then the long calm
# streets that don't have to keep waiting at semi-controlled intersections". A calm street is a
# road at LTS 1-2 in a calm run (`calm_run_m`, `pipeline.calm_roads`: broken at every junction
# with a busy road) of at least the ride layer's bar, RIDE_ROAD_RUN_MI; it carries `calm`, true
# or left out, which the map draws it above the other streets by (frontend/src/stressStyle.js,
# `drawPriority`).
CALM_STREET_RULE = (
    f"CASE WHEN s.stress_tier <= {CALM_ROAD_MAX_TIER} AND NOT s.is_trail_class "
    f"AND s.{CALM_RUN_COLUMN} >= {round(RIDE_ROAD_RUN_MI * METRES_PER_MILE)} THEN true END"
)


_MERGED = """
WITH bounds AS (SELECT ST_TileEnvelope(%(z)s, %(x)s, %(y)s) AS env),
features AS (
    SELECT {columns},
           ST_AsMVTGeom(
               ST_Simplify(ST_Collect(ST_Transform({geometry}, 3857)), %(unit)s),
               bounds.env, %(extent)s, %(buffer)s, true
           ) AS geom
    FROM {table} AS s, bounds
    WHERE s.geometry && ST_Transform(
              ST_TileEnvelope(%(z)s, %(x)s, %(y)s, margin => %(margin)s), 4326)
      {coverage}
      AND {where}
    GROUP BY {group_by}, bounds.env
)
SELECT '{table}'::regclass::oid,
       (SELECT ST_AsMVT(features.*, '{layer}', %(extent)s, 'geom') FROM features)
"""

# THE CITY GRID. The owner, 2026-10-21: "lts colored roads look very crowded at the nax zoom
# they show up in urban areas, but it's needed for rural ones", then, of thinner streets
# everywhere or only in the city: "City only, via a server flag". At z12-13 a feature
# carries `dense` (true, else nothing) where its ways lie in a square of DENSE_CELL_M a
# side, in EPSG:3857 metres, holding at least DENSE_ROAD_M of drawn road, counted where each
# way starts; there the map draws the main bike routes first and the plain streets from z14
# (frontend/src/stressStyle.js, CITY_LADDER). The squares are
# fixed on the projection's grid, and every way that starts in a square the tile touches is
# counted (any way within DENSE_CELL_M of the tile, whatever the coverage clip), so a square
# reads the same from each tile it is drawn in. A way starting further out than that is
# judged by a square counted in part; the segments are split at every junction, so in a grid
# none is that long. 12 km in a kilometre square (about 15 km of road a square kilometre on
# the ground at DC's latitude) is a downtown or rowhouse grid of 100-150 m blocks, where a
# suburb of loops and cul-de-sacs is about half that and a rural road a tenth. Tuned on the
# real map (2026-10-23, the live tiles of 2026-10-22 at z12.3): at 12 km only 36% of the squares
# in a view of central DC qualified, so most of Northwest, Northeast, Capitol Hill and
# Arlington kept every street ("There's still a lot of clutter"); at 8 km 64% of DC's squares
# do, against 31% around Gaithersburg, whose country roads still keep their lines.
DENSE_CELL_M = 1000
DENSE_ROAD_M = 8_000
DENSE_RULE = f"CASE WHEN cells.road_m >= {DENSE_ROAD_M} THEN true END"

_MERGED_DENSE = """
WITH bounds AS (SELECT ST_TileEnvelope(%(z)s, %(x)s, %(y)s) AS env),
cells AS (
    SELECT floor(ST_X(start) / {cell}) AS cx, floor(ST_Y(start) / {cell}) AS cy,
           sum(ST_Length(ST_Transform(s.geometry, 3857))) AS road_m
    FROM {table} AS s,
         LATERAL (SELECT ST_Transform(ST_StartPoint(s.geometry), 3857) AS start) AS p
    WHERE s.geometry && ST_Transform(
              ST_Expand(ST_TileEnvelope(%(z)s, %(x)s, %(y)s, margin => %(margin)s), {cell}), 4326)
      AND {where}
    GROUP BY 1, 2
),
features AS (
    SELECT {columns},
           ST_AsMVTGeom(
               ST_Simplify(ST_Collect(ST_Transform({geometry}, 3857)), %(unit)s),
               bounds.env, %(extent)s, %(buffer)s, true
           ) AS geom
    FROM {table} AS s
    CROSS JOIN bounds
    CROSS JOIN LATERAL (SELECT ST_Transform(ST_StartPoint(s.geometry), 3857) AS start) AS p
    LEFT JOIN cells
        ON cells.cx = floor(ST_X(p.start) / {cell}) AND cells.cy = floor(ST_Y(p.start) / {cell})
    WHERE s.geometry && ST_Transform(
              ST_TileEnvelope(%(z)s, %(x)s, %(y)s, margin => %(margin)s), 4326)
      {coverage}
      AND {where}
    GROUP BY {group_by}, bounds.env
)
SELECT '{table}'::regclass::oid,
       (SELECT ST_AsMVT(features.*, '{layer}', %(extent)s, 'geom') FROM features)
"""

_PER_SEGMENT = """
WITH bounds AS (SELECT ST_TileEnvelope(%(z)s, %(x)s, %(y)s) AS env),
features AS (
    SELECT {columns},
           ST_AsMVTGeom(ST_Transform({geometry}, 3857), bounds.env, %(extent)s, %(buffer)s, true)
               AS geom
    FROM {table} AS s, bounds
    WHERE s.geometry && ST_Transform(
              ST_TileEnvelope(%(z)s, %(x)s, %(y)s, margin => %(margin)s), 4326)
      {coverage}
      AND {where}
)
SELECT '{table}'::regclass::oid,
       (SELECT ST_AsMVT(features.*, '{layer}', %(extent)s, 'geom') FROM features)
"""


def _table() -> str:
    # The schema name comes from settings and is validated the way every DDL
    # naming it is; an identifier cannot be a query parameter.
    return f"{validate_schema_name(settings.SEGMENT_SCHEMA_LIVE)}.segment"


# The coverage box, as the clipped query reads it from its parameters.
_COVERAGE_BOX = "ST_MakeEnvelope(%(c_west)s, %(c_south)s, %(c_east)s, %(c_north)s, 4326)"


def zoomed_out_where(level: Level, optional: frozenset[str]) -> tuple[str, list[str]]:
    """The ways a zoomed-out level (one with a predicate) draws, over the segment table as
    `s`, and its popular and calm terms; `pipeline.bike_network` finds their stray bits."""
    has_car_free = CAR_FREE_COLUMN in optional
    where = level.predicate(FACILITY_COLUMN in optional, has_car_free)
    if level.long_trails is not None and all(c in optional for c in LONG_TRAIL_COLUMNS):
        rule = long_trails_predicate(level.long_trails, has_car_free)
        where = f"({where}) AND {rule}"
    extra = popular_and_calm(level, optional)
    if extra:
        where = " OR ".join([f"({where})", *extra])
    return where, extra


def tile_sql(level: Level, optional: frozenset[str] = frozenset(), clip: bool = False) -> str:
    """The level's query, carrying the optional columns in `optional` too, and
    with `clip`, drawing only what lies inside the coverage box."""
    template = _MERGED_DENSE if level.dense else _MERGED if level.merged else _PER_SEGMENT
    carried = {name: f"s.{column}" for name, column in PROPERTIES.items()}
    if TRAIL_BRIDGE_COLUMN in optional:
        carried["unpaved"] = BRIDGE_UNPAVED
    for name, column in OPTIONAL_PROPERTIES.items():
        if column in optional:
            carried[name] = OPTIONAL_EXPRESSIONS.get(name, f"s.{column}")
        elif name in FALLBACKS:
            carried[name] = FALLBACKS[name]
    if FACILITY_SHOWN_COLUMN in optional and FACILITY_COLUMN in optional:
        carried["facility"] = f"COALESCE(s.{FACILITY_SHOWN_COLUMN}, s.{FACILITY_COLUMN})"
    has_facility = FACILITY_COLUMN in optional
    has_car_free = CAR_FREE_COLUMN in optional
    # At every level (the owner, 2026-10-21: "And futher out obviously label the long ones"
    # ... "Basically anything long"): a z10-11 tile's trails are the long ones, so a name
    # splits its merged features by trail and no further.
    if all(c in optional for c in LONG_TRAIL_COLUMNS):
        # A corridor's name only at z10-11 (the levels that keep the popular corridors): from
        # z12 the base map names every street itself (PR #383 review).
        named = level.popular_min is not None and BIKE_POPULAR_COLUMN in optional
        carried["trail_name"] = trail_name_rule(has_facility, named)
    if CALM_RUN_COLUMN in optional:
        carried["calm"] = CALM_STREET_RULE
    if TRAIL_TAGS_COLUMN in optional and MTB_LEVEL_COLUMN in optional:
        for name, key in MTB_SCALE_PROPERTIES.items():
            tag = f"s.{TRAIL_TAGS_COLUMN} ->> '{key}'"
            carried[name] = f"CASE WHEN s.{MTB_LEVEL_COLUMN} IS NOT NULL THEN {tag} END"
    if level.predicate is not None:
        where, extra = zoomed_out_where(level, optional)
        if STRAY_ZOOM_COLUMN in optional:
            # A stray bit of what this zoom draws ("These bits too": `pipeline.bike_network`).
            where = f"({where}) AND s.{STRAY_ZOOM_COLUMN} < {level.min_zoom}"
        if MTB_ONLY_COLUMN in optional:
            # Every mountain-bike trail at every zoom (ZOOMED_OUT_MTB): the map draws them this far
            # out only in the Mountain Bike ride type, and every other ride type leaves them out.
            where = f"({where}) OR {ZOOMED_OUT_MTB}"
            extra = [*extra, ZOOMED_OUT_MTB]
        if has_car_free:
            # A road closed to cars at set times is in a zoomed-out tile that
            # would not otherwise hold it only for those times: it carries them
            # as `car_free_only`, and the map draws it only in one of them. A
            # way the level holds anyway keeps `car_free` as it is.
            kept = " OR ".join([f"({level.predicate(has_facility)})", *extra])
            expression = carried.pop("car_free")
            carried["car_free"] = f"CASE WHEN {kept} THEN {expression} END"
            carried["car_free_only"] = f"CASE WHEN NOT {kept} THEN {expression} END"
    else:
        where = level.where or "true"
    # Only a road is drawn: a public road a bicycle may not use is left to the
    # base map ("You can just leave the public roads where bikes aren't allowed
    # as unmarked, using the base map", OWNER-DECISIONS 89), and a way no
    # typical rider could use is not drawn (80, 82, 88). On a table without
    # the column the motorways are what the classifier recorded as motor-only.
    carried.pop("map_class", None)
    if MAP_CLASS_COLUMN in optional:
        # An alley is carried only at street level, marked `alley`, where the
        # map draws it only from close in, faint (OWNER-DECISIONS 100).
        if level.merged:
            where = f"({where}) AND s.{MAP_CLASS_COLUMN} = 'road'"
        else:
            where = f"({where}) AND s.{MAP_CLASS_COLUMN} IN ('road', 'alley')"
            carried["alley"] = f"CASE WHEN s.{MAP_CLASS_COLUMN} = 'alley' THEN true END"
    else:
        where = f"({where}) AND NOT {MOTOR_ONLY_RULE}"
    if level.dense:
        carried["dense"] = DENSE_RULE
    return template.format(
        table=_table(),
        cell=DENSE_CELL_M,
        where=where,
        geometry=f"ST_ClipByBox2D(s.geometry, {_COVERAGE_BOX})" if clip else "s.geometry",
        coverage=f"AND s.geometry && {_COVERAGE_BOX}" if clip else "",
        layer=LAYER,
        columns=", ".join(f"{expression} AS {name}" for name, expression in carried.items()),
        group_by=", ".join(carried.values()),
    )


class DrawTimedOut(Exception):
    """A tile draw ran past its statement timeout and was cancelled."""


def render(
    z: int,
    x: int,
    y: int,
    optional: frozenset[str] = frozenset(),
    timeout_ms: int | None = None,
) -> tuple[int, bytes]:
    """(the live table's oid, the tile's bytes) for a tile inside the zooms
    served, drawn under a `timeout_ms` statement timeout (DRAW_TIMEOUT_MS if
    none is given)."""
    if timeout_ms is None:
        timeout_ms = DRAW_TIMEOUT_MS
    level = level_for(z, optional)
    c_west, c_south, c_east, c_north = settings.COVERAGE_BBOX
    params = {
        "c_west": c_west,
        "c_south": c_south,
        "c_east": c_east,
        "c_north": c_north,
        "z": z,
        "x": x,
        "y": y,
        "extent": level.extent,
        "buffer": level.buffer,
        "margin": level.buffer / level.extent,
        # One tile unit, in metres of EPSG:3857: finer detail is not drawn.
        "unit": WORLD_M / 2**z / level.extent,
    }
    clip = straddles_coverage(z, x, y, level.buffer / level.extent)
    try:
        with transaction.atomic(), connection.cursor() as cursor:
            cursor.execute("SELECT set_config('statement_timeout', %s, true)", [str(timeout_ms)])
            # No JIT, at any level: the city grid's square sums (DENSE_RULE) lift the
            # planner's cost past jit_above_cost, and compiling took ten times as long as the
            # draw it was for (a synthetic downtown z13 tile, 2026-10-21: 400 ms with it,
            # 45 ms without).
            cursor.execute("SELECT set_config('jit', 'off', true)")
            cursor.execute(tile_sql(level, optional, clip), params)
            oid, tile = cursor.fetchone()
    except OperationalError as error:
        if getattr(error.__cause__, "sqlstate", None) == "57014":  # query_canceled
            raise DrawTimedOut(f"tile {z}/{x}/{y} ran past {timeout_ms} ms") from error
        raise
    return oid, bytes(tile or b"")


def live_state() -> tuple[int | None, frozenset[str], int]:
    """The live table's oid (None before any build), which of the optional columns it
    has, and its edit generation: how many road-panel edits it has had since it was
    promoted (`core.stress_edits`; 0 for a table nobody has edited)."""
    with connection.cursor() as cursor:
        cursor.execute(
            "SELECT t.oid, ARRAY(SELECT attname::text FROM pg_attribute WHERE attrelid = t.oid "
            "AND attname = ANY(%s) AND NOT attisdropped), "
            "COALESCE((SELECT g.generation FROM live_edit_generation g "
            "WHERE g.table_oid = t.oid), 0) "
            "FROM (SELECT to_regclass(%s)::oid AS oid) AS t",
            [
                [
                    *OPTIONAL_PROPERTIES.values(),
                    *LONG_TRAIL_COLUMNS,
                    CALM_RUN_COLUMN,
                    STRAY_ZOOM_COLUMN,
                    TRAIL_TAGS_COLUMN,
                ],
                _table(),
            ],
        )
        oid, columns, generation = cursor.fetchone()
    return oid, frozenset(columns or ()), int(generation)


def live_table() -> tuple[int | None, frozenset[str]]:
    """The live table's oid, or None before any build, and which of the
    optional columns it has."""
    oid, columns, _ = live_state()
    return oid, columns


