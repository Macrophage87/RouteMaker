@dataclass(frozen=True)
class Level:
    name: str
    min_zoom: int
    extent: int
    # Tile units drawn past each edge, so a line's casing is not cut at it.
    buffer: int
    # SQL over the segment table's columns, or None for every row.
    where: str | None
    # One feature per class, simplified, rather than one per segment.
    merged: bool
    # The predicate drawn from `pipeline.schema`, by (has facility, has car_free),
    # in place of `where`: the trails', or the busy roads'.
    predicate: object = None
    # The bars for the long-trails rule (`pipeline.schema.long_trails_predicate`),
    # or None to keep every way the predicate selects. Applied only to a table
    # that has all three long-trail columns (LONG_TRAIL_COLUMNS); on one
    # without, today's tiles are drawn.
    long_trails: LongTrails | None = None


