"""GET /tiles/stress/{z}/{x}/{y}.pbf: the traffic-stress overlay, as vector tiles.

The SHARED API CONTRACT: a Mapbox Vector Tile with one layer, "stress", whose
features come from the live segment table with the properties "tier" (1-4),
"trail" and "unpaved"; served for zooms 7 to 16, an empty tile (200, no
bytes) outside the coverage box or outside those zooms, generated by PostGIS's
ST_AsMVT, with Cache-Control, and no sign-in. What stands in for the sign-in is
the per-address limit (`core.ratelimit.TILES`), counted before anything else.

Tiles are drawn at three levels of detail, because the table has 1,357,800
segments and a tile holding every one of them is useless at region scale:
measured on the first promoted build, the z10 tile over downtown DC held
228,854 of them in 6.0 MB and took 3.5 s, and the z12 tile 47,392 in 1.2 MB.

The owner, 2026-09-29: "Zoom less than 12, show just bike paths and the
metro/MARC. 12 and 13, show LTS 3+, 14+ show show the quiet streets."
(OWNER-DECISIONS 73; "Zoomed out just show the trails." before it, 65, and
"Show roadside trails (Recommended)", 66). Zoom 12-13 changed on 2026-10-05
(391): "I'm more concerned with the places to ride than the places not to.",
and z12-13 became a "where to ride" layer with no busy road. It changed again
on 2026-10-17: "Show traffic stress a couple more zoom levels up", then, of the
busy roads and every street: "Both from 12". So from zoom 12 every road is
drawn, the busy ones and the quiet streets alike, and the ride layer is gone:

- `TRAILS` and `TRAILS_NEAR`, z7-10 and z11 (up to QUIET_STREETS_MIN_ZOOM - 1): the
  traffic-free paths and trails and nothing else (`pipeline.schema.trails_predicate`:
  what `routemaker.facility` calls a path, the protected ways that are trails of
  their own beside a road, and the roads closed to cars at set times, for
  those times), and of those only the long ones: "Also zoomed out, can we stick
  to mostly the longer trails, it's getting messy." (OWNER-DECISIONS 375,
  2026-10-04). A way is long when it is on a regional-or-larger bicycle route
  or a long walking route (not a local one: OWNER-DECISIONS 377) or in a named
  run of trail long enough (`pipeline.schema.long_trails_predicate`), with a
  higher bar for an unpaved way and a higher bar again at z10 than at z11; a
  road closed to cars at set times stays whatever its length (377). The rail
  stations draw over them from the front end.
- `STREETS`, z12 and z13 (QUIET_STREETS_MIN_ZOOM to SEGMENTS_MIN_ZOOM - 1): every
  segment FULL draws, the busy roads (faint there, in the front end: the owner,
  "Show them faintly", then "Make solid at 14"; OWNER-DECISIONS 76, 77), the quiet
  streets, the footways and the mountain-bike trails, but merged, as the levels
  below it are. One feature per segment does not fit at z12: on a synthetic
  downtown grid of 48,050 segments (2026-10-17, the density the first promoted
  build measured over downtown DC) the z12 tile was 1.33 MB with one feature
  each and 482 KB merged, and z13 345 KB against 148 KB (z14, one each, 90 KB;
  the real z14 tiles are at most 125 KB).
- `FULL`, from SEGMENTS_MIN_ZOOM: every segment, one feature each, the alleys
  too. The map asks for nothing past z14 - it draws z15-16 from the z14 tile
  (`STRESS_ZOOMS.max` in the front end's mapStyle.ts) - so z14 is the deepest
  zoom drawn ahead; z15-16 are still served, for the contract, and drawn on
  request.

Below SEGMENTS_MIN_ZOOM a tile carries one feature per distinct (tier, trail,
unpaved, facility) - every segment of a class collected into one multi-line
and simplified to the tile's grid - so the size is the drawn geometry and not
a per-segment overhead; the properties a feature carries are still exactly its
segments'. What each level selects is written once, in `pipeline.schema`,
where the overview's partial GiST index is created with the zoomed-out
predicate, so the planner can prove the index applies.

Caching: the tiles change only when a rebuild promotes a new segment table, and
the promoted table is a new relation each time, so the ETag is that table's
oid with this module's format version. A client that already has a tile gets
a 304 without the tile being drawn again, and a tile drawn once is kept in
`core.tile_cache`, so a request
for one is a lookup, not a draw. Every tile the map asks for, z10 to z14 over
the coverage box, is drawn ahead after every promotion (the owner, 2026-09-28:
"It takes a very long time to load those roads.", where it felt slow: "Zoomed
in (street level)"; OWNER-DECISIONS 63).

A draw (a tile not in the cache) takes an in-flight slot
(`ratelimit.TILES_IN_FLIGHT`) and runs under DRAW_TIMEOUT_MS: well under the
swap's 3 s lock timeout, so a promotion waiting for its lock behind a tile
draw normally takes it on the first attempt, and short enough that the slots
cannot hold workers for long. It is not a hard bound: PostgreSQL checks for the
cancel between steps, and one cold draw on a busy host was seen to end at
5.46 s. The swap's retries (five attempts) are what cover that. A draw
refused a slot, or cut off by the timeout, is answered 429 or 503 with
Retry-After, which the front end waits out.

Coverage: a tile straddling the edge of `settings.COVERAGE_BBOX` is drawn from
its segments clipped to the box, so nothing is drawn in the map's grey area.
"""

