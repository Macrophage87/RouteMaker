def level_for(z: int, optional: frozenset[str] = frozenset()) -> Level:
    """The level a tile at `z` is drawn at, on a table with the `optional` columns:
    z12-13 is the ride layer where there is a `calm_run_m` to draw it from, and the
    busy roads (what it was before OWNER-DECISIONS 391) where there is not."""
    level = next(level for level in LEVELS if z >= level.min_zoom)
    if level is BUSY and CALM_RUN_COLUMN in optional:
        return RIDE_LAYER
    return level


def tile_bounds(z: int, x: int, y: int) -> tuple[float, float, float, float]:
    """(west, south, east, north) in degrees."""
    n = 2**z

    def lat(row: int) -> float:
        return math.degrees(math.atan(math.sinh(math.pi * (1 - 2 * row / n))))

    return x / n * 360 - 180, lat(y + 1), (x + 1) / n * 360 - 180, lat(y)


def outside_coverage(z: int, x: int, y: int) -> bool:
    west, south, east, north = tile_bounds(z, x, y)
    c_west, c_south, c_east, c_north = settings.COVERAGE_BBOX
    return east < c_west or west > c_east or north < c_south or south > c_north


def straddles_coverage(z: int, x: int, y: int, margin: float) -> bool:
    """Whether the tile, with `margin` of its width drawn past each edge,
    reaches past the coverage box - and so has to be clipped to it."""
    west, south, east, north = tile_bounds(z, x, y)
    dx, dy = (east - west) * margin, (north - south) * margin
    c_west, c_south, c_east, c_north = settings.COVERAGE_BBOX
    return west - dx < c_west or east + dx > c_east or south - dy < c_south or north + dy > c_north


# Each feature's properties, as {tile property: segment column}: the one place
# that says what a tile carries. A value is carried as the column holds it, so
# a new tier value reaches the tile unchanged; a new property is a new entry
# here (and, if the zoomed-out levels should keep it, a term in
# pipeline.schema's predicates). A null is left out of the feature rather than
# sent - an unknown surface is not "paved".
PROPERTIES = {"tier": "stress_tier", "trail": "is_trail_class", "unpaved": "is_unpaved"}

# Properties carried only from a live table that has the column: the bike
# facility (path, protected, lane, none), which the rebuild writes from
# `routemaker.facility`, and a table promoted before it has no such column. Where it is
# there, the zoomed-out levels draw its paths and trails. Where it is not, a
# stand-in is carried in its place (`FALLBACKS`) and the zoomed-out paths are
# the ones that stand-in calls a path. `separate_bikeway` (true, or left out)
# is what the map draws a road beside a separately mapped bike facility faint
# by (OWNER-DECISIONS 73, 78). `map_class` is not carried: only a road is in
# the tiles at all (80, 82, 88, 89).
OPTIONAL_PROPERTIES = {
    "facility": FACILITY_COLUMN,
    "car_free": CAR_FREE_COLUMN,
    "map_class": MAP_CLASS_COLUMN,
    "separate_bikeway": SEPARATE_BIKEWAY_COLUMN,
    # NO-BIKE-PATHS (OWNER-DECISIONS 290, 291): `mtb` marks a trail only a
    # mountain bike rides (kept open for Gravel and Mountain Goat, closed for
    # the rest) and `rough` a surface that sheds riders. The map draws an `mtb`
    # trail in its own not-for-routes look, a thin dotted grey line, and in no
    # routable layer (452a, superseding 452's hiding and 290(b)'s faint drawing;
    # frontend/src/stressStyle.js, `mtb-trail`); a future MTB mode would draw it
    # as routable. `rough` is not read: such a trail draws as any unpaved one,
    # with no path rail (290(a)).
    # Each is true or left out.
    "mtb": MTB_ONLY_COLUMN,
    "rough": ROUGH_COLUMN,
    # OWNER-DECISIONS 403: a trail beside a road, which the map draws as a paved path
    # where no surface is mapped (not 376 A's surface-unknown dashes). True or left out.
    "roadside": ROADSIDE_COLUMN,
    # The Mass Ride capacity (OWNER-DECISIONS 325-327, 387), riders a minute, from the
    # usable width (404-407).
    "rpm": MASS_WIDTH_COLUMN,
}

# The tile property `rpm` is rounded down to a multiple of this (OPTIONAL_EXPRESSIONS).
RPM_STEP = 10
# Riders a minute for each metre of usable width, from `routemaker.flow`: the column holds
# the width, and the tile computes the riders, so tuning the constants needs no rebuild.
# But neither tile tag carries this figure, so a tuned constant must bump BOTH
# FORMAT_VERSIONs (this module's and core.mass_tiles'), or the tile cache and the
# browsers' 304s keep the old `rpm` while the route chart, computed at request time,
# moves at once (REBUILD-BUNDLE correctness review, nit 3).
# tests/test_stress_tiles.py holds the figure to the format versions it was drawn at.
RPM_PER_METRE_SQL = repr(round(flow.level_riders_per_min(1.0), 6))

# How an optional property is drawn from its column, where it is not the
# column as it is. `car_free`: the ride times a road closed to motor traffic
# at set times is car-free in, comma-separated ("weekend"), and left out of a
# feature that has none - a road closed for good is a path already. The map's
# style reads it against the ride time it follows (frontend/src/stressStyle.js,
# `stressFilters`): in one of them the road draws as an off-road path, tier 1,
# and otherwise with its own stress (the owner, 2026-09-29: "Car-free roads
# should be regarded the same as an off-road path on a map."; OWNER-DECISIONS
# 67). One tile serves every ride time, so the pre-draw draws each tile once.
OPTIONAL_EXPRESSIONS = {
    "car_free": f"NULLIF(array_to_string(s.{CAR_FREE_COLUMN}, ','), '')",
    "separate_bikeway": f"NULLIF(s.{SEPARATE_BIKEWAY_COLUMN}, false)",
    "mtb": f"NULLIF(s.{MTB_ONLY_COLUMN}, false)",
    "rough": f"NULLIF(s.{ROUGH_COLUMN}, false)",
    "roadside": f"NULLIF(s.{ROADSIDE_COLUMN}, false)",
    # `rpm`: the Mass Ride capacity, riders a minute, rounded DOWN to a multiple of
    # RPM_STEP. The Mass Ride bands (60, 120, 200) are multiples of it, so a
    # feature never moves band; and the zoomed-out levels, which collect every
    # segment of one value into one feature, are not split into a feature per
    # distinct figure (one per integer would be about 400 values a class).
    "rpm": (
        f"(floor(round(s.{MASS_WIDTH_COLUMN}::numeric * {RPM_PER_METRE_SQL}) / {RPM_STEP}.0)"
        f" * {RPM_STEP})::int"
    ),
}

# What an optional property is drawn from on a table without its column: the
# facility is derived from the trail network (an off-road path, or nothing),
# so the trails carry the path's rails at every zoom before the column exists;
# and a road beside a separate bikeway is not known, so none is drawn faint
# for it.
FALLBACKS = {"facility": TRAIL_NETWORK_FACILITY}

# The three columns the long-trails rule reads (OWNER-DECISIONS 375, 377), which the
# rebuild writes from the OSM route relations and way names
# (`pipeline.trail_routes`). Not carried in a tile: they only choose which ways
# the z10-11 tiles hold. A table promoted before them has none of them, and its
# zoomed-out tiles keep every path and trail, as they did; the rule applies
# only where all three are there. A data rebuild adds them; nothing else does.
LONG_TRAIL_COLUMNS = (TRAIL_ROUTE_COLUMN, TRAIL_RUN_COLUMN, TRAIL_BRIDGE_COLUMN)

_MERGED = """
WITH bounds AS (SELECT ST_TileEnvelope(%(z)s, %(x)s, %(y)s) AS env),
features AS (
    SELECT {columns},
           ST_AsMVTGeom(
               ST_Simplify(ST_Collect(ST_Transform({geometry}, 3857)), %(unit)s),
               bounds.env, %(extent)s, %(buffer)s, true
           ) AS geom
    FROM {table} AS s, bounds
    WHERE s.geometry && ST_Transform(
              ST_TileEnvelope(%(z)s, %(x)s, %(y)s, margin => %(margin)s), 4326)
      {coverage}
      AND {where}
    GROUP BY {group_by}, bounds.env
)
SELECT '{table}'::regclass::oid,
       (SELECT ST_AsMVT(features.*, '{layer}', %(extent)s, 'geom') FROM features)
"""

_PER_SEGMENT = """
WITH bounds AS (SELECT ST_TileEnvelope(%(z)s, %(x)s, %(y)s) AS env),
features AS (
    SELECT {columns},
           ST_AsMVTGeom(ST_Transform({geometry}, 3857), bounds.env, %(extent)s, %(buffer)s, true)
               AS geom
    FROM {table} AS s, bounds
    WHERE s.geometry && ST_Transform(
              ST_TileEnvelope(%(z)s, %(x)s, %(y)s, margin => %(margin)s), 4326)
      {coverage}
      AND {where}
)
SELECT '{table}'::regclass::oid,
       (SELECT ST_AsMVT(features.*, '{layer}', %(extent)s, 'geom') FROM features)
"""


def _table() -> str:
    # The schema name comes from settings and is validated the way every DDL
    # naming it is; an identifier cannot be a query parameter.
    return f"{validate_schema_name(settings.SEGMENT_SCHEMA_LIVE)}.segment"


# The coverage box, as the clipped query reads it from its parameters.
_COVERAGE_BOX = "ST_MakeEnvelope(%(c_west)s, %(c_south)s, %(c_east)s, %(c_north)s, 4326)"


def tile_sql(level: Level, optional: frozenset[str] = frozenset(), clip: bool = False) -> str:
    """The level's query, carrying the optional columns in `optional` too, and
    with `clip`, drawing only what lies inside the coverage box."""
    template = _MERGED if level.merged else _PER_SEGMENT
    carried = {name: f"s.{column}" for name, column in PROPERTIES.items()}
    for name, column in OPTIONAL_PROPERTIES.items():
        if column in optional:
            carried[name] = OPTIONAL_EXPRESSIONS.get(name, f"s.{column}")
        elif name in FALLBACKS:
            carried[name] = FALLBACKS[name]
    has_facility = FACILITY_COLUMN in optional
    has_car_free = CAR_FREE_COLUMN in optional
    if level.predicate is not None:
        where = level.predicate(has_facility, has_car_free)
        if level.long_trails is not None and all(c in optional for c in LONG_TRAIL_COLUMNS):
            rule = long_trails_predicate(level.long_trails, has_car_free)
            where = f"({where}) AND {rule}"
        if has_car_free:
            # A road closed to cars at set times is in a zoomed-out tile that
            # would not otherwise hold it only for those times: it carries them
            # as `car_free_only`, and the map draws it only in one of them. A
            # way the level holds anyway keeps `car_free` as it is.
            kept = level.predicate(has_facility)
            expression = carried.pop("car_free")
            carried["car_free"] = f"CASE WHEN {kept} THEN {expression} END"
            carried["car_free_only"] = f"CASE WHEN NOT {kept} THEN {expression} END"
    else:
        where = level.where or "true"
    # Only a road is drawn: a public road a bicycle may not use is left to the
    # base map ("You can just leave the public roads where bikes aren't allowed
    # as unmarked, using the base map", OWNER-DECISIONS 89), and a way no
    # typical rider could use is not drawn (80, 82, 88). On a table without
    # the column the motorways are what the classifier recorded as motor-only.
    carried.pop("map_class", None)
    if MAP_CLASS_COLUMN in optional:
        # An alley is carried only at street level, marked `alley`, where the
        # map draws it only from close in, faint (OWNER-DECISIONS 100).
        if level.merged:
            where = f"({where}) AND s.{MAP_CLASS_COLUMN} = 'road'"
        else:
            where = f"({where}) AND s.{MAP_CLASS_COLUMN} IN ('road', 'alley')"
            carried["alley"] = f"CASE WHEN s.{MAP_CLASS_COLUMN} = 'alley' THEN true END"
    else:
        where = f"({where}) AND NOT {MOTOR_ONLY_RULE}"
    return template.format(
        table=_table(),
        where=where,
        geometry=f"ST_ClipByBox2D(s.geometry, {_COVERAGE_BOX})" if clip else "s.geometry",
        coverage=f"AND s.geometry && {_COVERAGE_BOX}" if clip else "",
        layer=LAYER,
        columns=", ".join(f"{expression} AS {name}" for name, expression in carried.items()),
        group_by=", ".join(carried.values()),
    )


class DrawTimedOut(Exception):
    """A tile draw ran past its statement timeout and was cancelled."""


def render(
    z: int,
    x: int,
    y: int,
    optional: frozenset[str] = frozenset(),
    timeout_ms: int | None = None,
) -> tuple[int, bytes]:
    """(the live table's oid, the tile's bytes) for a tile inside the zooms
    served, drawn under a `timeout_ms` statement timeout (DRAW_TIMEOUT_MS if
    none is given)."""
    if timeout_ms is None:
        timeout_ms = DRAW_TIMEOUT_MS
    level = level_for(z, optional)
    c_west, c_south, c_east, c_north = settings.COVERAGE_BBOX
    params = {
        "c_west": c_west,
        "c_south": c_south,
        "c_east": c_east,
        "c_north": c_north,
        "z": z,
        "x": x,
        "y": y,
        "extent": level.extent,
        "buffer": level.buffer,
        "margin": level.buffer / level.extent,
        # One tile unit, in metres of EPSG:3857: finer detail is not drawn.
        "unit": WORLD_M / 2**z / level.extent,
    }
    clip = straddles_coverage(z, x, y, level.buffer / level.extent)
    try:
        with transaction.atomic(), connection.cursor() as cursor:
            cursor.execute("SELECT set_config('statement_timeout', %s, true)", [str(timeout_ms)])
            cursor.execute(tile_sql(level, optional, clip), params)
            oid, tile = cursor.fetchone()
    except OperationalError as error:
        if getattr(error.__cause__, "sqlstate", None) == "57014":  # query_canceled
            raise DrawTimedOut(f"tile {z}/{x}/{y} ran past {timeout_ms} ms") from error
        raise
    return oid, bytes(tile or b"")


def live_table() -> tuple[int | None, frozenset[str]]:
    """The live table's oid, or None before any build, and which of the
    optional columns it has."""
    with connection.cursor() as cursor:
        cursor.execute(
            "SELECT t.oid, ARRAY(SELECT attname::text FROM pg_attribute WHERE attrelid = t.oid "
            "AND attname = ANY(%s) AND NOT attisdropped) "
            "FROM (SELECT to_regclass(%s)::oid AS oid) AS t",
            [[*OPTIONAL_PROPERTIES.values(), *LONG_TRAIL_COLUMNS, CALM_RUN_COLUMN], _table()],
        )
        oid, columns = cursor.fetchone()
    return oid, frozenset(columns or ())


ETAG_LETTERS = {
    FACILITY_COLUMN: "f",
    CAR_FREE_COLUMN: "c",
    MAP_CLASS_COLUMN: "m",
    SEPARATE_BIKEWAY_COLUMN: "s",
    TRAIL_BRIDGE_COLUMN: "b",
    TRAIL_ROUTE_COLUMN: "t",
    TRAIL_RUN_COLUMN: "l",
    CALM_RUN_COLUMN: "k",
    MTB_ONLY_COLUMN: "o",
    ROUGH_COLUMN: "r",
    ROADSIDE_COLUMN: "e",
    # `w` for width: `r` is the rough surface's (the bundle's two branches both took it).
    MASS_WIDTH_COLUMN: "w",
}


def etag_for(oid: int, optional: frozenset[str] = frozenset()) -> str:
    # Weak: the same table always draws the same features, but not always the
    # same bytes - ST_AsMVT's feature and value order follows the scan's row
    # order, and two draws of one z14 tile measured 124,520 and 124,532 bytes.
    # A strong tag promises byte-identical bodies (RFC 9110 8.8.1). The
    # optional columns are in it because a column added to the live table in
    # place (the facility, by hand) changes the tiles but not the table's oid.
    # Each column by a letter of its own, so the tag fits the cache's 64-character
    # key with all of them (a `+` and one letter each, twelve in all: `W/"stress-` and a
    # ten-digit oid, `+` and twelve letters, `-v7"`, 37 characters), in the order of the
    # column names.
    carried = "".join(ETAG_LETTERS[column] for column in sorted(optional))
    return f'W/"stress-{oid}{"+" + carried if carried else ""}-v{FORMAT_VERSION}"'


def _matches(request, etag: str) -> bool:
    header = request.META.get("HTTP_IF_NONE_MATCH", "")
    if not header:
        return False
    # If-None-Match uses the weak comparison (RFC 9110 13.1.2): W/ or not,
    # the same opaque tag matches.
    tags = [tag.removeprefix("W/") for tag in parse_etags(header)]
    return "*" in tags or etag.removeprefix("W/") in tags


def _tile_response(body: bytes, status: int = 200, etag: str | None = None) -> HttpResponse:
    response = HttpResponse(body, status=status, content_type=CONTENT_TYPE)
    patch_cache_control(response, public=True, max_age=MAX_AGE_S)
    if etag is not None:
        response["ETag"] = etag
    return response


@require_http_methods(["GET", "HEAD"])
@ratelimit.rate_limited(ratelimit.TILES)
def stress_tile(request, z: int, x: int, y: int) -> HttpResponse:
    if z > MAX_ADDRESSABLE_ZOOM or x >= 2**z or y >= 2**z:
        response = JsonResponse({"error": "not a tile address"}, status=400)
        response["Cache-Control"] = "no-store"
        return response
    if not MIN_ZOOM <= z <= MAX_ZOOM or outside_coverage(z, x, y):
        return _tile_response(b"")
    oid, optional = live_table()
    if oid is None:
        # No build has been promoted: nothing to draw, and the front end hides
        # the overlay on a 404 rather than showing a legend for nothing.
        response = JsonResponse({"error": "no stress data has been built yet"}, status=404)
        response["Cache-Control"] = "no-store"
        return response
    etag = etag_for(oid, optional)
    if _matches(request, etag):
        return _tile_response(b"", status=304, etag=etag)
    cached = tile_cache.get(etag, z, x, y)
    if cached is not None:
        return _tile_response(cached, etag=etag)
    held, refusal = ratelimit.acquire(request, ratelimit.TILES_IN_FLIGHT)
    if refusal is not None:
        refusal["Cache-Control"] = "no-store"
        return refusal
    try:
        try:
            drawn_oid, body = render(z, x, y, optional)
        except DrawTimedOut:
            response = JsonResponse(
                {"error": "This part of the stress map is taking too long; try again shortly."},
                status=503,
            )
            response["Retry-After"] = str(RETRY_AFTER_S)
            response["Cache-Control"] = "no-store"
            return response
    finally:
        ratelimit.release(held)
    if drawn_oid == oid:
        # Not when a promotion landed between the lookup and the draw: this
        # body belongs to the new table, and its own requests will cache it.
        # The Mass Ride tiles share the cache (core.mass_tiles): an eviction keeps theirs.
        from . import mass_tiles

        tile_cache.put(etag, z, x, y, body, also_keep=(mass_tiles.etag_for(oid, optional),))
    return _tile_response(body, etag=etag_for(drawn_oid, optional))
